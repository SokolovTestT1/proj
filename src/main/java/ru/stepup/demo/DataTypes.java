package ru.stepup.demo;

/**
 * Класс DataTypes содержит информацию о типах данных в Java.
 * Ниже представлены комментарии с теорией и примерами.
 */

public class DataTypes {

    /*
     * В Java существует два типа данных:
     *
     * 1. Примитивные типы (primitive types) — встроенные типы, определённые языком.
     * 2. Ссылочные типы (reference types) — объекты, массивы, строки и т.д.
     *
     * ===============================================
     * 1. ПРИМИТИВНЫЕ ТИПЫ ДАННЫХ
     * ===============================================
     *
     * В Java 8 примитивных типов, они делятся на 4 группы:
     *
     * A. Целочисленные типы:
     *    - byte     : 8 бит   (-128 до 127)
     *    - short    : 16 бит  (-32,768 до 32,767)
     *    - int      : 32 бит  (-2^31 до 2^31-1)
     *    - long     : 64 бит  (-2^63 до 2^63-1)
     *
     * B. Вещественные (плавающая точка):
     *    - float    : 32 бит  (примерно ±3.4e38, точность ~6-7 знаков)
     *    - double   : 64 бит  (примерно ±1.7e308, точность ~15 знаков)
     *
     * C. Логический тип:
     *    - boolean  : true или false (размер не определён спецификацией)
     *
     * D. Символьный тип:
     *    - char     : 16 бит (Unicode символ, от '\u0000' до '\uffff')
     *
     * Примечание: Все примитивы имеют фиксированный размер независимо от платформы.
     */

    // Примеры объявления и инициализации примитивных типов:

    byte myByte = 100;                    // допустимые значения: -128..127
    short myShort = 30000;                // -32768..32767
    int myInt = 1_000_000;                // часто используется, по умолчанию
    long myLong = 9_223_372_036_854_775_807L; // обязательно 'L' в конце

    float myFloat = 3.14f;                // обязательно 'f' или 'F'
    double myDouble = 3.141592653589793;// по умолчанию для дробных

    boolean myBoolean = true;             // или false
    char myChar = 'A';                    // один символ в одинарных кавычках
    char myUnicodeChar = '\u0041';        // 'A' в Unicode

    /*
     * ===============================================
     * 2. ОБОЛОЧКИ (WRAPPER CLASSES)
     * ===============================================
     *
     * Для каждого примитивного типа существует соответствующий класс-обёртка:
     *
     *  byte      -> Byte
     *  short     -> Short
     *  int       -> Integer
     *  long      -> Long
     *  float     -> Float
     *  double    -> Double
     *  boolean   -> Boolean
     *  char      -> Character
     *
     * Обёртки нужны для:
     * - Хранения примитивов в коллекциях (например, ArrayList<Integer>)
     * - Использования null (примитивы не могут быть null)
     * - Вызова методов (например, Integer.parseInt("123"))
     *
     * Пример:
     */ Integer myInteger = 100;              // автоупаковка (autoboxing)
    int primitiveInt = myInteger;         // распаковка (unboxing)

    /*
     * ===============================================
     * 3. ССЫЛОЧНЫЕ ТИПЫ
     * ===============================================
     *
     * Это объекты, создаваемые через классы, интерфейсы, массивы.
     *
     * Примеры:
     */ String myString = "Hello, Java!";     // строка — ссылочный тип
    int[] myArray = {1, 2, 3};            // массив — ссылочный тип
    Object obj = new Object();            // любой объект

    /*
     * Отличия примитивов и ссылочных типов:
     *
     * | Примитивы                     | Ссылочные типы
     * |-------------------------------|----------------------------------
     * | Хранят значение               | Хранят ссылку на объект в куче
     * | Не могут быть null            | Могут быть null
     * | По умолчанию: 0, false, '\0'  | По умолчанию: null
     * | Передаются по значению        | Передаются по значению ссылки
     */

    /*
     * ===============================================
     * 4. ПРЕОБРАЗОВАНИЕ ТИПОВ
     * ===============================================
     *
     * A. Автоматическое (неявное) преобразование (widening):
     *    Меньший тип автоматически приводится к большему.
     *
     *    Пример:
     */ int a = 100;
    long b = a;  // OK: int -> long

    /*
     * B. Явное преобразование (сужающее, narrowing):
     *    Может привести к потере данных.
     */ long bigNumber = 1000L;
    int smallNumber = (int) bigNumber;  // явное приведение

    // Пример потери данных:
    byte c = (byte) 257;  // будет 1, так как 257 % 256 = 1

    /*
     * Особенности при работе с вещественными числами:
     */ double d1 = 0.1 + 0.2;
    // System.out.println(d1); // вывод: 0.30000000000000004
    // Причина: неточность представления чисел с плавающей точкой.

    // Решение: использовать BigDecimal для точных вычислений
    // import java.math.BigDecimal;
    // BigDecimal bd1 = new BigDecimal("0.1");
    // BigDecimal bd2 = new BigDecimal("0.2");
    // BigDecimal sum = bd1.add(bd2); // 0.3

    /*
     * ===============================================
     * 5. ИСКЛЮЧЕНИЯ И ОШИБКИ, СВЯЗАННЫЕ С ТИПАМИ
     * ===============================================
     *
     * A. ClassCastException
     *    Возникает при неверном приведении типов.
     */ Object objStr = "Hello";
    // String s = (Integer) objStr; // ClassCastException!

    /*
     * B. NullPointerException
     *    При попытке использовать null как объект.
     */ String nullStr = null;
    // int len = nullStr.length(); // NullPointerException

    /*
     * C. NumberFormatException
     *    При попытке парсить строку в число, если формат неверный.
     */
    // int bad = Integer.parseInt("abc"); // NumberFormatException

    /*
     * D. ArithmeticException
     *    Например, деление на ноль для целых чисел.
     */
    // int div = 5 / 0; // ArithmeticException: / by zero
    // Но: double d = 5.0 / 0; // результат: Infinity (не ошибка!)

    /*
     * ===============================================
     * 6. ПОЛЕЗНЫЕ СТАТИЧЕСКИЕ ПОЛЯ И МЕТОДЫ
     * ===============================================
     */
    void printTypeLimits() {
        System.out.println("Byte:    " + Byte.MIN_VALUE + " .. " + Byte.MAX_VALUE);
        System.out.println("Short:   " + Short.MIN_VALUE + " .. " + Short.MAX_VALUE);
        System.out.println("Integer: " + Integer.MIN_VALUE + " .. " + Integer.MAX_VALUE);
        System.out.println("Long:    " + Long.MIN_VALUE + " .. " + Long.MAX_VALUE);
        System.out.println("Float:   " + Float.MIN_VALUE + " .. " + Float.MAX_VALUE);
        System.out.println("Double:  " + Double.MIN_VALUE + " .. " + Double.MAX_VALUE);
    }

    /*
     * ===============================================
     * 7. ЗАКЛЮЧЕНИЕ
     * ===============================================
     *
     * - Используйте примитивы, когда возможно — они быстрее и легче.
     * - Используйте обёртки, когда нужна работа с коллекциями или null.
     * - Будьте осторожны с приведением типов и делением на ноль.
     * - Для финансовых вычислений — BigDecimal.
     * - Строки неизменяемы (immutable) — это важно!
     *
     * Это базовое понимание типов данных в Java.
     */

    public static void main(String[] args) {
        DataTypes dt = new DataTypes();
        dt.printTypeLimits();

        // Пример работы с типами
        System.out.println("char: " + dt.myChar);
        System.out.println("boolean: " + dt.myBoolean);
    }
}